async def portal_sync(tenant_id: UUID, customer_id: UUID, body: CredentialSync, session: AsyncSession = Depends(get_session)):
    """Customer Management -> legacy mirror, one direction only. Keeps the staff onboarding view truthful
    (activated / last sign-in) and the legacy hash current so a rollback does not lock customers out."""
