@router.get("/legacy-accounts")
async def legacy_accounts(offset: int = 0, limit: int = 200, session: AsyncSession = Depends(get_session)):
    """Accounts issued by the original post-issuance flow, for the one-time import into Customer Management.
    The bcrypt hash is what makes already-issued temporary passwords keep working; plaintext was never stored."""
    rows = (await session.exec(select(CustomerPortalAccount).order_by(CustomerPortalAccount.created_at)
                               .offset(max(offset, 0)).limit(min(max(limit, 1), 500)))).all()
    out = []
    for a in rows:
        customer = await session.get(Customer, a.customer_id)
        tenant = await session.get(Tenant, a.tenant_id)
        if customer is None or tenant is None or customer.organization_id or customer.family_group_id:
            continue
        out.append({
            "tenant_id": str(a.tenant_id), "tenant_code": tenant.code, "customer_id": str(a.customer_id), "username": a.username,
            "password_hash": a.password_hash, "display_name": customer.name, "legacy_status": a.status,
            "must_reset": a.must_reset, "credential_expires_at": _iso(a.invite_expires_at), "last_login_at": _iso(a.last_login_at),
            "created_at": a.created_at.isoformat()})
    return out


