class ContactUpdate(BaseModel):
    email: Optional[str] = PField(default=None, max_length=255)
    phone: Optional[str] = PField(default=None, max_length=30)
    address: Optional[str] = PField(default=None, max_length=500)
    actor: str = "customer"


_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
_PHONE_RE = re.compile(r"^\+?[0-9][0-9\s-]{6,18}[0-9]$")


@router.patch("/tenants/{tenant_id}/customers/{customer_id}/profile/contact")
async def update_contact(tenant_id: UUID, customer_id: UUID, body: ContactUpdate, request: Request,
                         session: AsyncSession = Depends(get_session)):
    """Contact details only. Name, CNIC, date of birth and the like go through the correction/approval process."""
    c = await _customer(session, tenant_id, customer_id)
    email = (body.email or "").strip() or None
    phone = (body.phone or "").strip() or None
    address = (body.address or "").strip() or None
    if not (email or phone or address):
        raise HTTPException(422, detail={"code": "VALIDATION", "message": "Provide an email, phone number or address"})
    if email and not _EMAIL_RE.match(email):
        raise HTTPException(422, detail={"code": "INVALID_EMAIL", "message": "Enter a valid email address"})
    if phone and not _PHONE_RE.match(phone):
        raise HTTPException(422, detail={"code": "INVALID_PHONE", "message": "Enter a valid phone number"})
    details = dict(c.details or {})
    changed = []
    if email:
        details["contact_email"] = email
        if "email" in details:
            details["email"] = email
        changed.append("email")
    if phone:
        details["contact_phone"] = phone
        for k in ("phone", "mobile_number"):
            if k in details:
                details[k] = phone
        changed.append("phone")
    if address:
        current = details.get("address")
        # Keep a structured address structured: replace only its street line.
        details["address"] = {**current, "street_address": address} if isinstance(current, dict) else address
        changed.append("address")
    c.details = details
    session.add(c)
    # Leave a trail on every live policy so staff see the change on the policy timeline.
    events = [record_event(session, p, event_type="CustomerContactUpdated", actor="customer-portal",
                           detail={"fields": changed}) for p in await _own_policies(session, tenant_id, customer_id)
              if _st(p) in IN_FORCE_STATUSES]
    await session.commit()
    return await profile(tenant_id, customer_id, session)


