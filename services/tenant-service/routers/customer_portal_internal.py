@router.get("/legacy-accounts")
async def legacy_accounts(offset: int = 0, limit: int = 200, session: AsyncSession = Depends(get_session)):
    """Accounts issued by the original post-issuance flow, for the one-time import into Customer Management.
    The bcrypt hash is what makes already-issued temporary passwords keep working; plaintext was never stored."""
    rows = (await session.exec(select(CustomerPortalAccount).order_by(CustomerPortalAccount.created_at)
                               .offset(max(offset, 0)).limit(min(max(limit, 1), 500)))).all()
    out = []
    for a in rows:
        customer = await session.get(Customer, a.customer_id)
        tenant = await session.get(Tenant, a.tenant_id)
        if customer is None or tenant is None or customer.organization_id or customer.family_group_id:
            continue
        out.append({
            "tenant_id": str(a.tenant_id), "tenant_code": tenant.code, "customer_id": str(a.customer_id), "username": a.username,
            "password_hash": a.password_hash, "display_name": customer.name, "legacy_status": a.status,
            "must_reset": a.must_reset, "credential_expires_at": _iso(a.invite_expires_at), "last_login_at": _iso(a.last_login_at),
            "created_at": a.created_at.isoformat()})
    return out


class CredentialSync(BaseModel):
    password_hash: Optional[str] = None
    must_reset: bool = False
    last_login_at: Optional[datetime] = None


@router.post("/tenants/{tenant_id}/customers/{customer_id}/portal-sync")
async def portal_sync(tenant_id: UUID, customer_id: UUID, body: CredentialSync, session: AsyncSession = Depends(get_session)):
    """Customer Management -> legacy mirror, one direction only. Keeps the staff onboarding view truthful
    (activated / last sign-in) and the legacy hash current so a rollback does not lock customers out."""
    portal = (await session.exec(select(CustomerPortalAccount).where(
        CustomerPortalAccount.customer_id == customer_id, CustomerPortalAccount.tenant_id == tenant_id))).first()
    if portal is None:
        raise HTTPException(404, "No portal account")
    if body.password_hash:
        portal.password_hash = body.password_hash
    portal.must_reset = body.must_reset
    portal.status = "Active"
    if body.last_login_at:
        portal.last_login_at = body.last_login_at.replace(tzinfo=None) if body.last_login_at.tzinfo else body.last_login_at
    portal.updated_at = datetime.utcnow()
    session.add(portal)
    await session.commit()
    return {"ok": True}
