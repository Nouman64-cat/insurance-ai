"""Endpoints only the Customer Management service may call (services/customer-management).

Every call must carry a valid HMAC signature made with CM_TO_TENANT_KEY and the caller name "customer-management"
(shared/security/service_auth.py). Nothing here is reachable through the API gateway.

The service is a thin, customer-safe window onto the EXISTING domain code — it re-implements no insurance rule:

  * policies / billing  -> services.billing_gate.compute_billing, routers.policies helpers
  * premium payment     -> routers.post_issuance.collect_installment (the same ledger, receipt and state machine)
  * claims              -> routers.claim_workflow.register_claim / receive_document (the same Claim + ClaimProcess)
  * documents           -> files already generated by those flows

Authorisation is decided HERE, on every call, from the (tenant_id, customer_id) the caller names — which Customer
Management takes from the signed-in account, never from the browser:

  1. the customer must exist in that tenant and be an individual (not an employee or family member);
  2. a policy must belong to that customer, be an individual policy (no master_policy_id / family_policy_id)
     and be in a customer-visible status;
  3. anything below a policy (installment, receipt, claim, document) is resolved THROUGH that policy.

A resource that exists but is not the customer's is reported as 404, exactly like one that does not exist.
Responses are allow-lists of fields: commission, fraud scores, underwriting notes and staff identities never appear.
"""

