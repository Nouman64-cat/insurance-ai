def _v(x) -> str:
    return x.value if hasattr(x, "value") else str(x)


def _iso(d) -> Optional[str]:
    return d.isoformat() if d else None


def mask_cnic(cnic: Optional[str]) -> Optional[str]:
    if not cnic:
        return None
    digits = re.sub(r"\D", "", cnic)
    if len(digits) == 13:
        return f"{digits[:5]}-*******-{digits[-1]}"
    return "*" * max(len(digits) - 2, 0) + digits[-2:]


def _address_text(a: Any) -> Optional[str]:
    """Addresses are stored either as a plain string (staff endorsements) or a structured object (seeded/captured data)."""
    if isinstance(a, dict):
        parts = [a.get("street_address") or a.get("address"), a.get("area"), a.get("city"), a.get("district"), a.get("province"), a.get("postal_code")]
        return ", ".join(str(x) for x in parts if x) or None
    return str(a) if a else None


def _contact(c: Customer) -> dict:
    d = c.details or {}
    contact = d.get("contact") if isinstance(d.get("contact"), dict) else {}
    return {
        "email": d.get("contact_email") or d.get("email") or contact.get("email") or None,
        "phone": d.get("contact_phone") or d.get("phone") or d.get("mobile_number") or contact.get("mobile_number") or None,
        "address": _address_text(d.get("address") or contact.get("address")),
    }


async def _customer(session: AsyncSession, tenant_id: UUID, customer_id: UUID) -> Customer:
    c = await session.get(Customer, customer_id)
    if c is None or c.tenant_id != tenant_id or c.organization_id or c.family_group_id:
        raise HTTPException(404, "Customer not found")
    return c


async def _owned_policy(session: AsyncSession, tenant_id: UUID, customer_id: UUID, policy_id: UUID) -> Policy:
    """Gates 1-2: the policy must be this individual customer's own, customer-visible policy."""
    policy = await session.get(Policy, policy_id)
    if (policy is None or policy.tenant_id != tenant_id or policy.customer_id != customer_id
            or policy.master_policy_id or policy.family_policy_id or _st(policy) not in VISIBLE_STATUSES):
        raise HTTPException(404, "Policy not found")
    return policy


async def _own_policies(session: AsyncSession, tenant_id: UUID, customer_id: UUID) -> list[Policy]:
    rows = (await session.exec(select(Policy).where(
        Policy.tenant_id == tenant_id, Policy.customer_id == customer_id,
        Policy.master_policy_id.is_(None), Policy.family_policy_id.is_(None)))).all()  # type: ignore[union-attr]
    return sorted([p for p in rows if _st(p) in VISIBLE_STATUSES], key=lambda p: p.created_at, reverse=True)


def _portal_actor(customer: Customer, account_id: Optional[str] = None) -> SimpleNamespace:
    """Stands in for the staff `User` the claim code expects. `id` stays None: the columns it feeds are nullable."""
    label = f"customer:{customer.policyholder_id or str(customer.id)[:8]}"
    return SimpleNamespace(id=None, email=label, username=label, full_name=customer.name)


