@router.post("/tenants/{tenant_id}/customers/{customer_id}/policies/{policy_id}/premiums/{schedule_id}/pay")
async def pay_installment(tenant_id: UUID, customer_id: UUID, policy_id: UUID, schedule_id: UUID, body: PayBody,
                          request: Request, session: AsyncSession = Depends(get_session)):
    """Pay the oldest unpaid installment through the existing collection path (simulated gateway).

    The browser never supplies an amount: `expected_amount` is only what the customer SAW, and a mismatch with what
    is payable now (e.g. a late surcharge started overnight) is refused so they can review the new figure."""
    policy = await _owned_policy(session, tenant_id, customer_id, policy_id, family="full")
    if _st(policy) not in IN_FORCE_STATUSES:
        raise HTTPException(409, detail={"code": "POLICY_NOT_PAYABLE", "message": "Premiums can only be paid while the policy is in force."})
    schedule = await session.get(PremiumSchedule, schedule_id)
    if schedule is None or schedule.policy_id != policy.id:
        raise HTTPException(404, "Installment not found")
    if schedule.status not in (PremiumScheduleStatusEnum.PENDING, PremiumScheduleStatusEnum.OVERDUE):
        raise HTTPException(409, detail={"code": "ALREADY_PAID", "message": "This installment is already settled."})
    unpaid = sorted([s for s in (await session.exec(select(PremiumSchedule).where(PremiumSchedule.policy_id == policy.id))).all()
                     if s.status in (PremiumScheduleStatusEnum.PENDING, PremiumScheduleStatusEnum.OVERDUE)],
                    key=lambda s: (s.due_date, s.installment_no))
    if unpaid and unpaid[0].id != schedule.id:
        raise HTTPException(409, detail={"code": "PAY_OLDEST_FIRST", "message": "Pay the earliest outstanding installment first."})
    payable = round(schedule.amount_due - schedule.amount_paid + surcharge_for(schedule.amount_due, _row_state(schedule, date.today())), 2)
    if abs(payable - body.expected_amount) > 0.009:
        raise HTTPException(409, detail={"code": "AMOUNT_CHANGED", "message": "The amount payable has changed.", "payable": payable})
    customer = await _customer(session, tenant_id, customer_id)
    try:
        await collect_installment(tenant_id, policy.id, schedule.id,
                                  CollectBody(method=body.method, reference=body.reference, manual=False, realize=True,
                                              collected_by=f"customer:{customer.policyholder_id or body.account_ref}"),
                                  request, session)
    except HTTPException as exc:
        if exc.status_code == 402:
            raise HTTPException(402, detail={"code": "PAYMENT_DECLINED", "message": "The payment was not completed. Nothing was charged."})
        if exc.status_code in (400, 409):
            await session.rollback()
            raise HTTPException(409, detail={"code": "ALREADY_PAID", "message": "This installment is already settled."})
        raise
    receipt = (await session.exec(select(PremiumReceipt).where(PremiumReceipt.schedule_id == schedule.id)
                                  .order_by(PremiumReceipt.created_at.desc()))).first()  # type: ignore[attr-defined]
    return {"status": "PAID", "simulated": True, "receipt": _receipt_view(receipt) if receipt else None}


