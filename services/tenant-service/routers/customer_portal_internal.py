def _customer_stages(proc: ClaimProcess, claim: Claim, paid: float) -> list[dict]:
    """The seven steps, in customer wording. Internal labels/details (red flags, referrals) are dropped on purpose."""
    stages = {s["key"]: s for s in eng.project_stages(proc, claim, payout_total=paid)}
    out = []
    for n, key in enumerate(STAGE_KEYS, 1):
        s = stages.get(key)
        state = s["state"] if s else "pending"
        out.append({"key": key, "step": n, "state": {"complete": "complete", "current": "current", "action": "current",
                                                      "exception": "attention", "skipped": "skipped"}.get(state, "pending")})
    return out


async def _claim_detail(session: AsyncSession, policy: Policy, claim: Claim, proc: Optional[ClaimProcess]) -> dict:
    row = await _claim_row(session, policy, claim, proc)
    payouts = (await session.exec(select(ClaimPayout).where(ClaimPayout.claim_id == claim.id))).all()
    paid = round(sum(p.amount for p in payouts if p.status in ("Completed", "Paid", "Reconciled", "Settled")), 2)
    detail: dict = {**row, "stages": None, "documents": [], "timeline": [], "decision": None, "eligibility": None,
                    "settlement": None, "event": None}
    if proc is None:
        return detail
    st = _v(claim.status)
    detail["stages"] = _customer_stages(proc, claim, paid)
    detail["event"] = {"date": proc.event_date.isoformat(), "end_date": _iso(proc.event_end_date), "place": proc.event_place,
                       "cause": proc.event_cause, "description": proc.event_description}
    detail["eligibility"] = ({"status": proc.eligibility_status, "message": (proc.eligibility_json or {}).get("message")}
                             if proc.eligibility_status else None)
    prog = eng.documents_progress(proc.documents_json)
    detail["documents"] = [{"key": d["key"], "label": d["label"], "required": d["required"], "status": d["status"],
                            "received_at": d.get("received_at"), "file_name": d.get("file_name"),
                            "can_upload": d["status"] in ("Requested", "Pending", "Returned", "Rejected") and st not in ("Approved", "Partial Approval", "Declined", "Settled", "Closed")}
                           for d in (proc.documents_json or []) if d["status"] != "Waived"]
    detail["documents_progress"] = {"received": prog["received"], "required": prog["required"], "complete": prog["complete"]}
    if st in ("Approved", "Partial Approval", "Declined", "Settled", "Closed"):
        detail["decision"] = {"decision": proc.decision, "amount": proc.decision_amount, "reason": proc.decision_reason,
                              "at": _iso(proc.decision_at)}
    if payouts:
        detail["settlement"] = {"paid_total": paid, "payouts": [
            {"amount": p.amount, "method": p.method, "status": p.status, "reference": p.reference_number,
             "completed_at": _iso(p.completed_at)} for p in payouts]}
    events = (await session.exec(select(PolicyEvent).where(PolicyEvent.policy_id == policy.id)
                                 .order_by(PolicyEvent.created_at.desc()))).all()  # type: ignore[attr-defined]
    detail["timeline"] = [{"id": str(e.id), "title": CLAIM_EVENT_TITLES[e.event_type], "at": e.created_at.isoformat()}
                          for e in events if e.event_type in CLAIM_EVENT_TITLES and (e.detail_json or {}).get("claim_no") == claim.claim_number]
    return detail


