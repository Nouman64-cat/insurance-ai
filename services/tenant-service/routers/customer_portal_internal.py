async def signed_by_customer_management(request: Request) -> None:
    key = os.environ.get("CM_TO_TENANT_KEY", "")
    path = request.url.path + (f"?{request.url.query}" if request.url.query else "")
    # Multipart uploads are parsed by FastAPI before dependencies run, so the raw body is not available here: the signature
    # for those covers method, path (customer, claim and document ids) and time, with an empty body.
    body = b"" if request.headers.get("content-type", "").startswith("multipart/form-data") else await request.body()
    if not key or request.headers.get(CALLER_HEADER) != CALLER or not verify(key, request.method, path, body, request.headers):
        raise HTTPException(401, detail={"code": "SERVICE_AUTH_FAILED", "message": "Invalid service signature"})


router.dependencies.append(Depends(signed_by_customer_management))


