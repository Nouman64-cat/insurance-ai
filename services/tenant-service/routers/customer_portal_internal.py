@router.get("/tenants/{tenant_id}/customers/{customer_id}/documents")
async def list_documents(tenant_id: UUID, customer_id: UUID, segment: str = "individual", session: AsyncSession = Depends(get_session)):
    customer = await _customer(session, tenant_id, customer_id)
    if segment not in ("individual", "family", "all"):
        raise HTTPException(422, detail={"code": "VALIDATION", "message": "Unknown segment"})
    out: list[dict] = []
    if segment in ("individual", "all"):
        for p in await _own_policies(session, tenant_id, customer_id):
            out.extend(await _documents(session, p))
    if segment in ("family", "all"):
        for p, access in await fam.family_policies_for(session, tenant_id, customer, full_only=True):
            out.extend({**d, "segment": "family", "family_name": access.family_name} for d in await _documents(session, p, customer, access))
    return sorted(out, key=lambda d: d["date"] or "", reverse=True)


def _file_response(path: str, filename: str, media: str = "application/pdf") -> Response:
    if not path or not os.path.isfile(path):
        raise HTTPException(404, "The document is not available")
    return FileResponse(path, media_type=media, filename=filename.replace("/", "-"))


@router.get("/tenants/{tenant_id}/customers/{customer_id}/documents/download")
async def download_document(tenant_id: UUID, customer_id: UUID, handle: str, session: AsyncSession = Depends(get_session)):
    """`handle` = kind:policy_id:item_id from the listing. Ownership is checked through the policy; unknown kinds 404."""
    customer = await _customer(session, tenant_id, customer_id)
    try:
        kind, pid, item = handle.split(":", 2)
        policy, access = await _owned_policy_access(session, tenant_id, customer_id, UUID(pid), family="full")
    except (ValueError, HTTPException):
        raise HTTPException(404, "The document is not available")

    async def get(model, ident, field="policy_id"):
        try:
            row = await session.get(model, UUID(ident))
        except ValueError:
            row = None
        if row is None or getattr(row, field) != policy.id:
            raise HTTPException(404, "The document is not available")
        return row

    if kind == "policy_document":
        d = await get(PolicyDocument, item)
        return _file_response(d.storage_url or "", f"{d.document_name}.pdf")
    if kind == "welcome_kit":
        ob = (await session.exec(select(PolicyOnboarding).where(PolicyOnboarding.policy_id == policy.id))).first()
        return _file_response(ob.welcome_kit_path if ob else "", f"{(ob.welcome_kit_name if ob else None) or 'welcome_kit'}.pdf")
    if kind == "receipt":
        r = await get(PremiumReceipt, item)
        return _file_response(r.document_path or "", f"{r.receipt_no}.pdf")
    if kind == "endorsement":
        e = await get(PolicyEndorsement, item)
        return _file_response(e.document_path or "", f"endorsement_{e.endorsement_no}.pdf")
    if kind == "renewal_confirmation":
        r = await get(PolicyRenewal, item)
        return _file_response(r.confirmation_path or "", "renewal_confirmation.pdf")
    if kind == "reinstatement_confirmation":
        r = await get(PolicyReinstatement, item)
        return _file_response(r.confirmation_path or "", "reinstatement_confirmation.pdf")
    if kind == "exit_confirmation":
        r = await get(PolicyExit, item)
        return _file_response(r.confirmation_path or "", "policy_exit_confirmation.pdf")
    if kind in ("claim_checklist", "claim_confirmation", "claim_document"):
        claim_id = item.split(".", 1)[0]
        claim = await get(Claim, claim_id)
        proc = (await session.exec(select(ClaimProcess).where(ClaimProcess.claim_id == claim.id))).first()
        if proc is None or not await _claim_visible(session, customer, access, claim, proc):
            raise HTTPException(404, "The document is not available")
        if kind == "claim_checklist":
            from routers.claim_workflow import _render_checklist
            return _file_response(await _render_checklist(session, policy, claim, proc), f"claim_checklist_{claim.claim_number}.pdf")
        if kind == "claim_confirmation":
            return _file_response(proc.confirmation_path or "", f"claim_closure_{claim.claim_number}.pdf")
        doc = next((d for d in (proc.documents_json or []) if d["key"] == item.split(".", 1)[-1] and d.get("artifact_id")), None)
        art = await session.get(Artifact, UUID(doc["artifact_id"])) if doc else None
        if art is None or art.tenant_id != tenant_id or art.claim_id != claim.id:
            raise HTTPException(404, "The document is not available")
        if art.storage_url and art.storage_url.startswith("local://"):
            return _file_response(os.path.join("/app/shared/storage", art.storage_url.replace("local://", "")), art.file_name,
                                  art.file_type or "application/octet-stream")
        url = _presign_url(art.storage_url.split(".amazonaws.com/", 1)[-1]) if art.storage_url else ""
        if not url:
            raise HTTPException(404, "The document is not available")
        async with httpx.AsyncClient(timeout=30) as client:
            resp = await client.get(url)
        if resp.status_code != 200:
            raise HTTPException(404, "The document is not available")
        return Response(resp.content, media_type=art.file_type or "application/octet-stream",
                        headers={"Content-Disposition": f'attachment; filename="{art.file_name}"'})
    raise HTTPException(404, "The document is not available")


