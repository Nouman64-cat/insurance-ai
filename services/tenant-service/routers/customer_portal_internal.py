async def _documents(session: AsyncSession, policy: Policy) -> list[dict]:
    """Everything downloadable for one policy. `id` is an opaque handle; file paths never leave this service."""
    pid, out = str(policy.id), []

    def add(kind: str, item: str, title: str, when, ok: bool, **extra: Any) -> None:
        out.append({"id": f"{kind}:{pid}:{item}", "kind": kind, "title": title, "policy_id": pid,
                    "policy_number": policy.policy_number, "date": _iso(when), "available": bool(ok), **extra})

    titles = {"PolicySchedule": "Policy schedule", "CertificateOfInsurance": "Certificate of insurance",
              "PolicyWording": "Policy wording", "PremiumNotice": "Premium notice", "RenewalNotice": "Renewal notice"}
    for d in (await session.exec(select(PolicyDocument).where(PolicyDocument.policy_id == policy.id))).all():
        add("policy_document", str(d.id), titles.get(_v(d.document_type), d.document_name), d.generated_at,
            d.storage_url and os.path.exists(d.storage_url))
    ob = (await session.exec(select(PolicyOnboarding).where(PolicyOnboarding.policy_id == policy.id))).first()
    if ob and ob.welcome_kit_path:
        add("welcome_kit", pid, "Welcome kit", ob.welcome_kit_generated_at, os.path.exists(ob.welcome_kit_path))
    for r in (await session.exec(select(PremiumReceipt).where(PremiumReceipt.policy_id == policy.id)
                                 .order_by(PremiumReceipt.created_at.desc()))).all():  # type: ignore[attr-defined]
        add("receipt", str(r.id), f"Premium receipt {r.receipt_no}", r.created_at, r.document_path and os.path.exists(r.document_path),
            amount=r.total_amount)
    for e in (await session.exec(select(PolicyEndorsement).where(PolicyEndorsement.policy_id == policy.id))).all():
        add("endorsement", str(e.id), f"Endorsement {e.endorsement_no} — {e.endorsement_type}", e.created_at,
            e.document_path and os.path.exists(e.document_path))
    for r in (await session.exec(select(PolicyRenewal).where(PolicyRenewal.policy_id == policy.id))).all():
        if r.confirmation_path:
            add("renewal_confirmation", str(r.id), "Renewal confirmation", getattr(r, "updated_at", None) or r.created_at,
                os.path.exists(r.confirmation_path))
    for r in (await session.exec(select(PolicyReinstatement).where(PolicyReinstatement.policy_id == policy.id))).all():
        if r.confirmation_path:
            add("reinstatement_confirmation", str(r.id), "Reinstatement confirmation", r.created_at, os.path.exists(r.confirmation_path))
    for r in (await session.exec(select(PolicyExit).where(PolicyExit.policy_id == policy.id))).all():
        if r.confirmation_path:
            add("exit_confirmation", str(r.id), "Policy exit confirmation", r.created_at, os.path.exists(r.confirmation_path))
    for proc in (await session.exec(select(ClaimProcess).where(ClaimProcess.policy_id == policy.id))).all():
        claim = await session.get(Claim, proc.claim_id)
        if claim is None:
            continue
        if proc.documents_json:
            add("claim_checklist", str(claim.id), f"Claim {claim.claim_number} — document checklist", proc.checklist_generated_at, True)
        if proc.confirmation_path:
            add("claim_confirmation", str(claim.id), f"Claim {claim.claim_number} — closure letter", proc.confirmation_generated_at,
                os.path.exists(proc.confirmation_path))
        for item in proc.documents_json or []:
            if item.get("artifact_id"):
                add("claim_document", f"{claim.id}.{item['key']}", f"Claim {claim.claim_number} — {item.get('label')}",
                    item.get("received_at") and datetime.fromisoformat(item["received_at"]), True)
    return out


async def _timeline(session: AsyncSession, policy: Policy) -> list[dict]:
    rows = (await session.exec(select(PolicyEvent).where(PolicyEvent.policy_id == policy.id)
                               .order_by(PolicyEvent.created_at.desc()))).all()  # type: ignore[attr-defined]
    out = []
    for e in rows:
        title = TIMELINE_TITLES.get(e.event_type)
        if not title:
            continue
        d = e.detail_json or {}
        detail: dict = {}
        if e.event_type == "PremiumCollected":
            detail = {"amount": d.get("total"), "receipt_no": d.get("receipt_no")}
        elif e.event_type.startswith("Claim"):
            detail = {"claim_number": d.get("claim_no")}
        out.append({"id": str(e.id), "event": e.event_type, "title": title, "at": e.created_at.isoformat(),
                    "to_status": e.to_status, "detail": detail})
    return out


