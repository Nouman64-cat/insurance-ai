"use client";

import { useState } from "react";
import { suggestRuleValues } from "@/app/services/ruleEngine";
import { plainFieldLabel } from "./constants";
import { tx } from "@/lib/i18n/tx";

interface Props {
  field: string;
  values: string[];
  onChange: (values: string[]) => void;
}

const SPARK = (
  <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round" className="h-4 w-4" aria-hidden="true">
    <path d="M9.937 15.5A2 2 0 0 0 8.5 14.063l-6.135-1.582a.5.5 0 0 1 0-.962L8.5 9.936A2 2 0 0 0 9.937 8.5l1.582-6.135a.5.5 0 0 1 .963 0L14.063 8.5A2 2 0 0 0 15.5 9.937l6.135 1.581a.5.5 0 0 1 0 .964L15.5 14.063a2 2 0 0 0-1.437 1.437l-1.582 6.135a.5.5 0 0 1-.963 0z" /><path d="M20 3v4" /><path d="M22 5h-4" />
  </svg>
);

/** A list of keywords for a "contains any of" condition — typed by hand or generated by AI from a prompt. */
export default function KeywordListEditor({ field, values, onChange }: Props) {
  const [draft, setDraft] = useState("");
  const [showAi, setShowAi] = useState(values.length === 0);
  const [prompt, setPrompt] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [suggested, setSuggested] = useState<string[]>([]);
  const [note, setNote] = useState("");
  const label = plainFieldLabel(field);

  const add = (raw: string) => {
    const words = raw.split(/[,\n]/).map((w) => w.trim().toLowerCase()).filter(Boolean);
    const next = [...values];
    for (const w of words) if (!next.includes(w)) next.push(w);
    onChange(next);
  };

  const generate = async () => {
    const tenantId = localStorage.getItem("tenant_id");
    if (!tenantId || !prompt.trim()) return;
    setBusy(true);
    setError("");
    setSuggested([]);
    try {
      const res = await suggestRuleValues(tenantId, { field, field_label: label, prompt: prompt.trim(), existing: values });
      setSuggested(res.values);
      setNote(res.note);
      if (res.values.length === 0) setError(tx("No new keywords were suggested. Try describing it differently."));
    } catch (err: any) {
      setError(err.response?.data?.detail || err.message || tx("The AI could not generate a list."));
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="w-full space-y-3 rounded-xl border border-slate-200 bg-white p-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <p className="text-[11px] font-medium text-slate-500">
          {values.length === 0
            ? tx("Matches when the {0} contains any of these words.", { 0: label.toLowerCase() })
            : tx("{0} keywords — matches when the {1} contains any of them.", { 0: values.length, 1: label.toLowerCase() })}
        </p>
        <div className="flex items-center gap-2">
          {values.length > 0 && (
            <button type="button" onClick={() => onChange([])} className="text-[11px] font-medium text-slate-400 hover:text-red-600">{tx("Clear all")}</button>
          )}
          <button
            type="button"
            onClick={() => setShowAi((v) => !v)}
            className="inline-flex items-center gap-1.5 rounded-lg bg-fuchsia-50 px-2.5 py-1 text-[11px] font-semibold text-fuchsia-700 ring-1 ring-fuchsia-100 hover:bg-fuchsia-100"
          >
            {SPARK}{tx("Generate with AI")}
          </button>
        </div>
      </div>

      {showAi && (
        <div className="space-y-2 rounded-xl bg-fuchsia-50/40 p-3 ring-1 ring-fuchsia-100">
          <label className="block text-xs font-medium text-slate-700">
            {tx("Describe the list you want")}
            <textarea
              rows={2}
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              onKeyDown={(e) => { if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) generate(); }}
              placeholder={tx("e.g. Occupations with a high accidental-death risk in Pakistan — security, mining, heavy driving, work at heights")}
              className="mt-1 w-full rounded-xl border border-slate-200 bg-white px-3 py-2 text-xs font-normal text-slate-800 focus:border-fuchsia-300 focus:outline-none focus:ring-2 focus:ring-fuchsia-100"
            />
          </label>
          <div className="flex items-center gap-2">
            <button
              type="button"
              disabled={busy || prompt.trim().length < 3}
              onClick={generate}
              className="inline-flex items-center gap-1.5 rounded-xl bg-fuchsia-600 px-3.5 py-1.5 text-xs font-semibold text-white shadow-sm hover:bg-fuchsia-700 disabled:opacity-50"
            >
              {busy ? <span className="h-3.5 w-3.5 animate-spin rounded-full border-2 border-fuchsia-200 border-t-white" /> : SPARK}
              {busy ? tx("Generating…") : tx("Generate")}
            </button>
            <span className="text-[11px] text-slate-400">{tx("You review the list before it is used.")}</span>
          </div>
          {error && <p className="text-xs text-red-600">{error}</p>}
          {suggested.length > 0 && (
            <div className="space-y-2 pt-1">
              {note && <p className="text-[11px] text-slate-500">{note}</p>}
              <p className="text-[11px] font-medium text-slate-600">{tx("Suggested — tap ✕ to drop any you don't want:")}</p>
              <div className="flex max-h-40 flex-wrap gap-1.5 overflow-y-auto">
                {suggested.map((w) => (
                  <span key={w} className="inline-flex items-center gap-1 rounded-full bg-white px-2.5 py-1 text-[11px] text-slate-700 ring-1 ring-fuchsia-200">
                    {w}
                    <button type="button" onClick={() => setSuggested(suggested.filter((x) => x !== w))} className="text-slate-400 hover:text-red-600" aria-label={tx("Drop {0}", { 0: w })}>✕</button>
                  </span>
                ))}
              </div>
              <div className="flex gap-2">
                <button
                  type="button"
                  onClick={() => { add(suggested.join(",")); setSuggested([]); setShowAi(false); setPrompt(""); }}
                  className="rounded-xl bg-slate-900 px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-slate-800"
                >
                  {tx("Add {0} to the list", { 0: suggested.length })}
                </button>
                <button type="button" onClick={() => setSuggested([])} className="rounded-xl border border-slate-200 bg-white px-3.5 py-1.5 text-xs font-semibold text-slate-600 hover:bg-slate-50">
                  {tx("Discard")}
                </button>
              </div>
            </div>
          )}
        </div>
      )}

      {values.length > 0 && (
        <div className="flex max-h-44 flex-wrap gap-1.5 overflow-y-auto">
          {values.map((w) => (
            <span key={w} className="inline-flex items-center gap-1 rounded-full bg-slate-100 px-2.5 py-1 text-[11px] text-slate-700">
              {w}
              <button type="button" onClick={() => onChange(values.filter((x) => x !== w))} className="text-slate-400 hover:text-red-600" aria-label={tx("Remove {0}", { 0: w })}>✕</button>
            </span>
          ))}
        </div>
      )}

      <input
        value={draft}
        onChange={(e) => setDraft(e.target.value)}
        onKeyDown={(e) => {
          if ((e.key === "Enter" || e.key === ",") && draft.trim()) { e.preventDefault(); add(draft); setDraft(""); }
        }}
        onBlur={() => { if (draft.trim()) { add(draft); setDraft(""); } }}
        placeholder={tx("Type a word and press Enter (or paste a comma-separated list)")}
        className="w-full rounded-xl border border-slate-200 px-3 py-2 text-xs text-slate-800 focus:border-blue-300 focus:outline-none focus:ring-2 focus:ring-blue-100"
      />
    </div>
  );
}
